for code, fn in FILES.items():
    p = os.path.join(MODDIR, fn)
    m = json.load(io.open(p, encoding="utf-8"))
    n = 0
    for s in m["steps"]:
        k = (code, s["no"])
        if k not in ADD: continue
        s.setdefault("prompts", [])
        have = {x["label"] for x in s["prompts"]}
        for pr in ADD[k]:
            if pr["label"] not in have:
                s["prompts"].append(pr); n += 1
    io.open(p, "w", encoding="utf-8").write(json.dumps(m, ensure_ascii=False, indent=1))
    tot = sum(len(s.get("prompts", [])) for s in m["steps"])
    print("[OK] %s  프롬프트 +%d  → 합계 %d" % (code, n, tot))
