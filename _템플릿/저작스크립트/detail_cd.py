def run():
    for code, fn in FILES.items():
        p = os.path.join(MODDIR, fn)
        m = json.load(io.open(p, encoding="utf-8"))
        n_pan = n_ex = n_tr = n_ck = 0
        for s in m["steps"]:
            k = (code, s["no"])
            if k in PANEL and "panel" not in s:
                s["panel"] = PANEL[k]; n_pan += 1
            if k in EXPECT and not s.get("expect"):
                s["expect"] = EXPECT[k]; n_ex += 1
            if k in TROUBLE:
                s.setdefault("troubles", [])
                have = {t["when"] for t in s["troubles"]}
                for t in TROUBLE[k]:
                    if t["when"] not in have:
                        s["troubles"].append(t); n_tr += 1
            if k in CHECK:
                s.setdefault("checks", [])
                for c in CHECK[k]:
                    if c not in s["checks"]:
                        s["checks"].append(c); n_ck += 1
        g = m["guide"]; add = GUIDE_ADD[code]
        for box in add.get("intentBox", []):
            if box not in g["intentBox"]: g["intentBox"].append(box)
        for row in add.get("stuck", []):
            if row[0] not in [r[0] for r in g["stuck"]]: g["stuck"].append(row)
        for nx in add.get("next", []):
            if nx not in g["next"]: g["next"].append(nx)
        io.open(p, "w", encoding="utf-8").write(json.dumps(m, ensure_ascii=False, indent=1))
        print("[OK] %s  안내판+%d  예시+%d  대처+%d  확인+%d  | 막힘 %d  의도 %d"
              % (code, n_pan, n_ex, n_tr, n_ck, len(g["stuck"]), len(g["intentBox"])))

if __name__ == "__main__":
    run()
